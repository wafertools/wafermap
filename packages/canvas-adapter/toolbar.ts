// ── Image save ───────────────────────────────────────────────────────────────

/**
 * Host hook for persisting a rendered PNG. When supplied, the toolbar calls this
 * instead of triggering a browser `<a download>`, letting embedded hosts (Tauri,
 * Electron, WebView2) route the blob through a native save dialog or upload.
 * Receives the PNG `blob` and a `suggestedName` (already includes `.png`).
 */
export type SaveImageHandler = (blob: Blob, suggestedName: string) => void | Promise<void>;

/**
 * Persist a rendered PNG blob. Routes through the host `onSaveImage` hook when
 * provided; otherwise falls back to a browser `<a download>` click. Single
 * source of truth for the save action across `renderWaferMap` and
 * `renderWaferGallery` — neither should reimplement the `<a download>` dance.
 *
 * @param blob          the PNG blob (e.g. from `canvas.toBlob`)
 * @param filename      filename without extension (e.g. `'wafermap'`)
 * @param onSaveImage   optional host hook; when present, bypasses `<a download>`
 */
export function saveImageBlob(blob: Blob, filename: string, onSaveImage?: SaveImageHandler): void {
  const suggestedName = `${filename}.png`;
  if (onSaveImage) {
    void onSaveImage(blob, suggestedName);
    return;
  }
  const url = URL.createObjectURL(blob);
  const a   = document.createElement('a');
  a.href = url;
  a.download = suggestedName;
  a.click();
  URL.revokeObjectURL(url);
}

/**
 * Host hook for saving a text file (CSV, etc). Mirrors `SaveImageHandler` —
 * when provided, `saveTextFile` calls this instead of triggering a browser
 * `<a download>`, letting embedded hosts (Tauri, Electron, WebView2) route
 * the text through a native save dialog. Receives the raw `text`, a
 * `suggestedName` (already includes its extension), and the `mimeType`.
 */
export type SaveTextHandler = (text: string, suggestedName: string, mimeType: string) => void | Promise<void>;

/**
 * Persist a text file (e.g. a CSV export). Routes through the host
 * `onSaveText` hook when provided; otherwise falls back to a browser
 * `<a download>` click — the same `<a download>` dance `saveImageBlob` uses
 * for PNG saves, which is silently a no-op in Tauri/Electron/WebView2 (see
 * `saveImageBlob`'s own doc comment), hence the hook.
 *
 * @param text        the file contents
 * @param filename    filename including extension (e.g. `'test-values.csv'`)
 * @param mimeType    e.g. `'text/csv'`
 * @param onSaveText  optional host hook; when present, bypasses `<a download>`
 */
export function saveTextFile(text: string, filename: string, mimeType: string, onSaveText?: SaveTextHandler): void {
  if (onSaveText) {
    void onSaveText(text, filename, mimeType);
    return;
  }
  const blob = new Blob([text], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a   = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

// ── Accessibility ──────────────────────────────────────────────────────────────
//
// Toolbar buttons already carry `ariaLabel` (see makeBtn). Deliberately NO `title`
// attribute on toolbar buttons — it duplicates the custom hover tooltip. The
// helpers below add the menu/menuitem semantics and keyboard navigation that
// `aria-label` alone cannot provide, without rendering any native tooltip.

/** Selector matching every focusable menu item within a menu container. */
const MENU_ITEM_SELECTOR = '[role="menuitem"],[role="menuitemradio"],[role="menuitemcheckbox"]';

/**
 * Run `fn` on the next animation frame, falling back to a macrotask in
 * environments without `requestAnimationFrame` (e.g. JSDOM under tests).
 * Used to defer focus moves until the element is laid out, and to schedule
 * re-renders after a resize.
 *
 * Accepts an explicit `ownerWindow` — a bare `requestAnimationFrame` reference
 * resolves to whichever window this MODULE was first evaluated in (the host
 * page's), not necessarily the window whose layout the caller actually cares
 * about. For a gallery card detached into its own popup window, scheduling
 * against the opener's rAF loop means the callback only fires when the OPENER
 * repaints (e.g. on mouse movement there) — not when the popup itself does,
 * which reads as "the map doesn't resize until I move focus back to the main
 * window." Passing the popup's own `window` fixes this.
 */
export function nextFrame(fn: () => void, ownerWindow: Window = window): void {
  const raf = ownerWindow.requestAnimationFrame;
  if (typeof raf === 'function') raf.call(ownerWindow, fn);
  else setTimeout(fn, 0);
}

/**
 * Wire roving-focus keyboard navigation onto an already-roled menu:
 * ArrowUp/Down move between items, Home/End jump to ends, Enter/Space activate
 * the focused item, Escape (or Tab) closes the menu and returns focus to the
 * trigger. `close` should remove the menu and clear any open-menu bookkeeping.
 * Focus moves to the first item on open. Returns nothing; the listener lives on
 * the menu element and dies with it.
 */
/**
 * Roving keyboard focus over a live list of options — Arrow/Home/End to move,
 * Enter/Space to activate, Escape/Tab to dismiss.
 *
 * Deliberately does NOT move focus itself: that is the one thing the two
 * callers genuinely disagree about. A toolbar menu wants its first item focused
 * on open; the searchable list in `chartShell.ts` must leave focus on its
 * search box, and had its own copy of this whole switch for that single
 * difference — thirty duplicated lines guarding one line of divergence.
 *
 * `items()` is called per keystroke, not captured: the searchable list filters
 * its rows as you type, and a snapshot would navigate rows that are no longer
 * shown.
 */
export function wireListNavigation(
  container: HTMLElement,
  items: () => HTMLElement[],
  dismiss: () => void,
): void {
  container.addEventListener('keydown', (e: KeyboardEvent) => {
    const list = items();
    if (list.length === 0) return;
    const current = container.ownerDocument.activeElement as HTMLElement | null;
    const idx = current ? list.indexOf(current) : -1;

    switch (e.key) {
      case 'ArrowDown':
        e.preventDefault();
        list[idx < 0 || idx === list.length - 1 ? 0 : idx + 1].focus();
        break;
      case 'ArrowUp':
        e.preventDefault();
        list[idx <= 0 ? list.length - 1 : idx - 1].focus();
        break;
      case 'Home':
        e.preventDefault();
        list[0].focus();
        break;
      case 'End':
        e.preventDefault();
        list[list.length - 1].focus();
        break;
      case 'Enter':
      case ' ':
        if (idx >= 0) { e.preventDefault(); list[idx].click(); }
        break;
      case 'Escape':
      case 'Tab':
        e.preventDefault();
        dismiss();
        break;
    }
  });
}

function wireMenuKeyboard(menu: HTMLElement, trigger: HTMLElement | null, close: () => void): void {
  const items = (): HTMLElement[] => Array.from(menu.querySelectorAll<HTMLElement>(MENU_ITEM_SELECTOR));
  wireListNavigation(menu, items, () => { close(); trigger?.focus(); });

  // The part a searchable list must NOT do — see `wireListNavigation`.
  // Move focus into the menu so arrow keys work immediately on open.
  const first = items()[0];
  if (first) nextFrame(() => first.focus());
}

// Menus and the tooltip must be appended inside the nearest overlay root, not
// always document.body:
//
// - A wmap-own maximized modal/floating-window box (marked `wmap-overlay-box`)
//   is a fixed stacking context that would obscure body-level menus/tooltip.
// - A HOST's own modal built on the native <dialog> element, shown via
//   `.showModal()`, is promoted into the browser's top layer — a rendering
//   layer that paints above the ENTIRE normal stacking order unconditionally.
//   No z-index on a body-level element (however high `--wmap-z` is set) can
//   ever paint above top-layer content; the only fix is to make the overlay a
//   DESCENDANT of that dialog, so it's part of the same top-layer subtree.
//   `:modal` is the standard CSS pseudo-class matching precisely this case
//   (a <dialog> shown via showModal, not a plain `.show()`/`open`-attribute
//   dialog, which never enters the top layer and needs no special handling).
//
// The fallback is the ANCHOR's own document.body, not the bare global
// `document` — a gallery card detached into its own popup window (see
// renderWaferGallery.ts) has no ancestor overlay box (a real OS window needs
// none), so falling through to the wrong document would silently render its
// menus in the opener's page instead of inside the popup.
export function overlayRootFor(anchor: Element): Element {
  let el: Element | null = anchor;
  while (el) {
    if (el.classList.contains('wmap-overlay-box')) return el;
    if (el.tagName === 'DIALOG' && (el as HTMLDialogElement).matches(':modal')) return el;
    el = el.parentElement;
  }
  return anchor.ownerDocument.body;
}

// ── Shared menu layer ─────────────────────────────────────────────────────────
//
// One persistent element per overlay root, reserved for transient
// menus/dropdowns/cascade-submenus. `menuLayerFor` returns it; every menu this
// library builds appends into it instead of `overlayRootFor(anchor)` directly.
//
// This exists because relying on a shared NUMBER (Z_BASE, Z_ABOVE, ...) for
// "is this above that" only holds if nothing between the two compared
// elements breaks the chain — and in this codebase that chain has broken
// three times in one day: a persistent, sticky element (a gallery's toolbar +
// legend, pinned while its cards scroll underneath) needs to (a) sit above
// per-card content that ALSO uses an explicit z-index, while (b) staying
// below that same toolbar's own popped-out menu, which — before this layer
// existed — used the exact same z tier as the per-card content in (a). There
// is no single number that is simultaneously greater than and less than
// another instance of itself; every fix that reached for "just raise the
// number" broke one side or the other. See renderWaferGallery.ts's
// `gridEl`/`stickyHeaderEl` comments for the specific chain that kept
// reopening this.
//
// The structural fix is to stop menus from competing on that shared scale at
// all. A menu lives in this dedicated layer, at `Z_MENU` — fixed, reserved,
// and never used for anything else — so no persistent chrome anywhere in the
// library (present or future) can ever accidentally outrank a menu just by
// picking a bigger sticky/fixed z-index of its own. The layer sits above
// `Z_BASE`/`Z_ABOVE` (ordinary chrome, tooltips) and below `Z_ABOVE2`
// (content that must clear a maximized modal), matching where menus already
// needed to sit — this doesn't change the ordering, it makes the ordering
// impossible to accidentally violate from the "chrome" side.
//
// Reuses `overlayRootFor`'s own root resolution first — a menu opened from a
// toolbar living inside a host's own native `<dialog>` (or a wmap modal box)
// must still nest inside THAT container, or the browser's own top-layer
// stacking (for `<dialog>`) would put it behind the dialog regardless of any
// z-index. This layer is then a persistent child of whichever root that is,
// cached per root so repeated calls reuse the same node rather than stacking
// up duplicates.
const menuLayers = new WeakMap<Element, HTMLDivElement>();

export function menuLayerFor(anchor: Element): HTMLElement {
  const root = overlayRootFor(anchor);
  const existing = menuLayers.get(root);
  if (existing && existing.isConnected) return existing;
  const doc = anchor.ownerDocument;
  const layer = doc.createElement('div');
  layer.dataset.wmapMenuLayer = '1';
  Object.assign(layer.style, {
    position:      'fixed',
    inset:         '0',
    // Reserved exclusively for this layer — see the block comment above.
    zIndex:        Z_MENU,
    // The layer itself must never intercept a click over empty space; each
    // menu appended into it sets its own `pointer-events: auto`, same as
    // every menu already did when appending straight to `overlayRootFor`.
    pointerEvents: 'none',
  } as Partial<CSSStyleDeclaration>);
  root.appendChild(layer);
  menuLayers.set(root, layer);
  return layer;
}

// ── Tooltip ────────────────────────────────────────────────────────────────────
//
// There is exactly ONE tooltip element for the whole document, shared by every
// renderWaferMap, every renderWaferGallery, and all their toolbars. This is a
// hard invariant: only one tooltip may ever be visible at a time. Because every
// consumer points at the same node, "showing" a tooltip anywhere inherently
// hides whatever was shown elsewhere — they are the same element, it just moves
// and re-renders. This makes a stuck/frozen tooltip structurally impossible: the
// next hover anywhere reclaims and repositions the single node. (Previously each
// instance created its own body-appended element; a missed leave/cancel event on
// one left its tooltip frozen while the others kept working.)
//
// The singleton lives for the page lifetime — like a browser's native tooltip
// layer, it is reused, never destroyed. Instance teardown hides it rather than
// removing it, since other instances may still be using it.

// One tooltip PER DOCUMENT, not one for the whole process — a gallery card
// detached into its own popup window (see renderWaferGallery.ts's
// openWindowForCard) has an entirely separate `document`, and a tooltip
// created in the opener's document would render invisibly behind/outside that
// popup. Keyed by document so every render target (the host page, and any
// number of detached popup documents) gets its own single-instance tooltip,
// preserving the original "stuck tooltip is structurally impossible" guarantee
// within each document independently.
const sharedTooltips = new WeakMap<Document, HTMLDivElement>();

/** The shared tooltip element for `doc` (default: the host page's own
 * document), lazily created and appended to `doc.body`. */
export function getTooltip(doc: Document = document): HTMLDivElement {
  const existing = sharedTooltips.get(doc);
  if (existing && existing.isConnected) return existing;
  const el = existing ?? doc.createElement('div');
  if (!existing) {
    Object.assign(el.style, {
      position:     'fixed',
      pointerEvents:'none',
      background:   'rgba(30, 32, 40, 0.93)',
      color:        '#f0f0f2',
      border:       '1px solid rgba(255,255,255,0.10)',
      padding:      '7px 11px',
      borderRadius: RADIUS.control,
      fontSize:     FONT.sub,
      lineHeight:   LEADING.base,
      maxWidth:     '280px',
      // Hard height cap so the tooltip can never grow into a full-viewport block —
      // a safety net (the hover content is now compact, and pointerEvents:none means
      // it can't scroll, so anything beyond the cap, e.g. abundant host metadata, is
      // clipped rather than overflowing the screen).
      maxHeight:    'min(60vh, 480px)',
      overflow:     'hidden',
      whiteSpace:   'pre-wrap',
      zIndex:       Z_ABOVE,
      display:      'none',
      fontFamily:   FONT.family,
      boxShadow:    SHADOW.menu,
    });
    sharedTooltips.set(doc, el);
  }
  doc.body.appendChild(el);
  return el;
}

/** Hide `doc`'s shared tooltip. Deliberately does NOT re-home it to `doc.body`
 * — it stays wherever `reparentTooltip()` last placed it (e.g. inside an open
 * floating window's box). A non-modal floating window can stay open for many
 * ordinary hover/unhover cycles; snapping the tooltip back to `<body>` on
 * every hide (as this used to do) meant the very first unhover after opening
 * a floating window silently evicted the tooltip from the window's stacking
 * context, and it was never reparented back in — every subsequent hover in
 * that window then rendered the tooltip at `<body>`'s z-index, BEHIND the
 * window. Callers that actually close an overlay (see `openOverlay`'s
 * `close()`) are responsible for reparenting the tooltip back to `<body>`
 * themselves once the box that owned it is really going away. */
export function hideTooltip(doc: Document = document): void {
  const el = sharedTooltips.get(doc);
  if (!el) return;
  el.style.display = 'none';
}

/**
 * Move `parent`'s document's shared tooltip into `parent` (e.g. a maximized
 * modal box that creates its own stacking/overflow context). Pass nothing to
 * re-home the host page's tooltip to `document.body`.
 */
export function reparentTooltip(parent?: HTMLElement): void {
  const doc = parent?.ownerDocument ?? document;
  const el = getTooltip(doc);
  (parent ?? doc.body).appendChild(el);
}

/**
 * Position the shared tooltip near (clientX, clientY), re-homing it under
 * `anchor`'s nearest overlay root first (see overlayRootFor) if it isn't there
 * already. Re-resolving on every call is deliberate and cheap (a short
 * ancestor walk) — anchor's overlay root can change over the tooltip's
 * lifetime (e.g. a host opens its own <dialog> around an already-rendered
 * map), and the `parentElement !==` guard means the DOM is only actually
 * touched when the root has changed, not on every mousemove.
 */
/**
 * Place the tooltip near the cursor without covering the thing it describes.
 *
 * `anchor` used to be consulted only for `overlayRootFor` — placement was
 * computed from the cursor point alone, and since `y` starts ABOVE the cursor
 * (`clientY - 8`) the box then extended down over whatever was being pointed at.
 * On the map canvas that is harmless and in fact necessary: the anchor is the
 * whole canvas, so "don't overlap the anchor" would push the tooltip off the map
 * entirely. On a small anchor — a bar, a badge, a row, an icon button — there IS
 * somewhere else to go, and covering it while describing it is a real defect.
 *
 * So the anchor's box is avoided only when the anchor is small enough for that to
 * be feasible: flip to just below it, else just above it. A large anchor keeps
 * exactly the previous cursor-following behaviour.
 */
export function positionTooltip(tooltip: HTMLDivElement, anchor: Element, clientX: number, clientY: number): void {
  const root = overlayRootFor(anchor);
  if (tooltip.parentElement !== root) root.appendChild(tooltip);
  const ownerWindow = tooltip.ownerDocument.defaultView ?? window;
  tooltip.style.left = '0';
  tooltip.style.top  = '0';
  const tw     = tooltip.offsetWidth;
  const th     = tooltip.offsetHeight;
  const margin = 8;
  const vw     = ownerWindow.innerWidth;
  const vh     = ownerWindow.innerHeight;

  let x = clientX + 14;
  let y = clientY - 8;
  if (x + tw + margin > vw) x = clientX - tw - 6;

  const r = anchor.getBoundingClientRect();
  // 40% of the viewport: below this an anchor is a discrete control or datum with
  // room beside it; above it (the map canvas, a full-height panel) there is no
  // "beside", and displacing the tooltip that far would be worse than overlapping.
  const canAvoid = r.height > 0 && r.height <= vh * 0.4;
  if (canAvoid) {
    const overlapsAnchor = y < r.bottom && y + th > r.top && x < r.right && x + tw > r.left;
    if (overlapsAnchor) {
      const below = r.bottom + margin;
      const above = r.top - th - margin;
      // Prefer below (reading order, and the cursor is usually travelling down);
      // fall back to above; if neither fits, leave the cursor-relative position
      // and let the viewport clamps below deal with it.
      if (below + th + margin <= vh)  y = below;
      else if (above >= margin)       y = above;
    }
  }

  if (y + th + margin > vh) y = vh - th - margin;
  if (y < margin) y = margin;
  tooltip.style.left = `${x}px`;
  tooltip.style.top  = `${y}px`;
}

/**
 * Wire the shared themed tooltip onto a plain DOM element.
 *
 * Hoisted out of `maplessSummary.ts`, which had the only copy — and whose comment
 * already recorded why this exists: a native `title` is a different, browser-native
 * tooltip, slow to appear (OS hover delay) and in an unthemed system font/colour,
 * while every hover surface built through `createToolbarHelpers` uses this instant
 * dark one. `summaryPanel.ts` and the hand-built expand buttons in
 * `renderWaferMap`/`renderWaferGallery` were still on `title`.
 *
 * `text` may be a string, a getter (for a hint that changes with the control's own
 * state, e.g. the findings severity chips' show/hide), or omitted to live-read the
 * element's `aria-label` at hover time — the same thing `makeBtn` does, so a
 * control whose label changes with its state (expand ⇄ reattach) stays correct
 * without re-wiring.
 *
 * `asDataPoint` is for an element that is NOT already a control: it makes the
 * element a tab stop, announces it as a single datum (`role="img"`), and sets
 * `aria-label`, so the tooltip's content reaches the keyboard and a screen reader
 * (WCAG 1.4.13 — content shown on hover must be reachable and dismissable without
 * a pointer). Never pass it for a `<button>`: that would add a nested focus stop
 * and overwrite the control's own accessible name.
 */
export function wireTooltip(
  target: HTMLElement,
  text?: string | (() => string),
  opts: { asDataPoint?: boolean } = {},
): void {
  const resolve = () =>
    (typeof text === 'function' ? text() : text) ?? target.getAttribute('aria-label') ?? '';
  if (opts.asDataPoint) {
    target.tabIndex = 0;
    target.setAttribute('role', 'img');
    if (typeof text === 'string') target.setAttribute('aria-label', text);
  }
  const show = (e?: MouseEvent) => {
    const body = resolve();
    if (!body) return;
    const tooltip = getTooltip(target.ownerDocument);
    tooltip.textContent = body;
    tooltip.style.display = 'block';
    if (e) {
      positionTooltip(tooltip, target, e.clientX, e.clientY);
    } else {
      // Keyboard focus carries no pointer coordinates — anchor to the element's
      // own box instead of a cursor position that doesn't exist.
      const r = target.getBoundingClientRect();
      positionTooltip(tooltip, target, r.left + r.width / 2, r.top);
    }
  };
  const hide = () => hideTooltip(target.ownerDocument);
  target.addEventListener('mousemove', show);
  target.addEventListener('mouseleave', hide);
  target.addEventListener('focus', () => show());
  target.addEventListener('blur', hide);
}

