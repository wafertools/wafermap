export type ModeEntry = { plotMode: PlotMode; activeTest?: number; activeMetadataKey?: string; label: string; logScale?: boolean };

/**
 * Which plot modes the data actually supports — the single derivation shared by
 * `renderWaferMap` and `renderWaferGallery`.
 *
 * This is a correctness surface, not a convenience: the library's rule is that UI
 * controls must derive validity from the data the library built, never from a
 * caller-supplied flag. Two copies of that derivation can silently disagree about
 * which modes are offered (and adding a new plot mode means remembering both),
 * so it lives here with the rest of the shared toolbar primitives.
 *
 * `includeStacked` is the one genuine difference between the two callers, and is
 * a deliberate parameter rather than an inferred value: stacked modes are valid
 * for `renderWaferMap` only when the result was built from a `lotStack`
 * (`view.isLotStack`), whereas `renderWaferGallery` aggregates across its own
 * items and can always offer them.
 */
export function buildDataModeEntries(
  dies: Die[],
  testDefs: TestDef[] | undefined,
  options: { includeStacked: boolean },
): { testEntries: ModeEntry[]; binEntries: ModeEntry[]; stackedEntries: ModeEntry[] } {
  // Value modes need a numeric measurement or a recorded verdict (functional
  // tests); stacked values need numeric values specifically.
  const hasTestData = dies.some(dieHasTestData);
  const hasValues = dies.some(d => d.testValues !== undefined && Object.keys(d.testValues).length > 0);
  const hasHbin = dies.some(d => d.hbin != null);
  const hasSbin = dies.some(d => d.sbin != null);

  // `testDefs === undefined` means nobody described any tests, and discovering
  // bare numbers from the dies is the right fallback. An empty ARRAY is a
  // different statement — the caller reconciled and kept nothing (the files
  // disagree about every test number) — and falling back there would offer
  // exactly the tests that were withheld, under bare "Test N" labels, pooling
  // measurements the reconciliation had just ruled incomparable.
  const testEntries: ModeEntry[] = hasTestData
    ? (testDefs !== undefined
        ? testDefs.map(t => ({
            plotMode: 'value' as PlotMode,
            activeTest: t.testNumber,
            label: t.unit ? `${t.name} (${t.unit})` : t.name,
            logScale: t.logScale,
          }))
        : getUniqueTestNumbers(dies).map(tn => ({
            plotMode: 'value' as PlotMode,
            activeTest: tn,
            label: `Test ${tn}`,
          })))
    : [];

  const binEntries: ModeEntry[] = [
    ...(hasHbin ? [{ plotMode: 'hardBin' as PlotMode, label: MODE_LABELS.hardBin }] : []),
    ...(hasSbin ? [{ plotMode: 'softBin' as PlotMode, label: MODE_LABELS.softBin }] : []),
  ];

  const stackedEntries: ModeEntry[] = options.includeStacked ? [
    ...(hasValues ? [{ plotMode: 'stackedValues'   as PlotMode, label: MODE_LABELS.stackedValues }]   : []),
    ...(hasHbin   ? [{ plotMode: 'stackedBins'     as PlotMode, label: MODE_LABELS.stackedBins }]     : []),
    ...(hasSbin   ? [{ plotMode: 'stackedSoftBins' as PlotMode, label: MODE_LABELS.stackedSoftBins }] : []),
  ] : [];

  return { testEntries, binEntries, stackedEntries };
}

/**
 * True when at least one die actually carries a value for this metadata key.
 * Presence in `metadataFields` is an opt-in declaration; this is the "and there
 * is data for it" half of the same check, shared so the single map and the
 * gallery can't disagree on which fields to offer.
 */
export function metadataKeyHasData(dies: Die[], key: string): boolean {
  return dies.some(d => d.metadata?.[key] !== undefined && d.metadata?.[key] !== null);
}

/** A configured metadata field → its mode-menu entry, with the shared label fallback. */
export function metadataModeEntry(field: MetadataFieldDef): ModeEntry {
  return {
    plotMode: 'metadata' as PlotMode,
    activeMetadataKey: field.key,
    label: field.label ?? prettyKey(field.key),
  };
}

/**
 * A text input for filtering a list of rows by their label text, meant to sit
 * at the top of a scrollable menu/list once it gets long enough that scanning
 * beats scrolling. Shared by the plot-mode test-value cascade submenu here and
 * the chart test picker (`chartShell.ts`'s `makeSearchableTestSelect`) so both
 * get the same filter-as-you-type box instead of building it twice.
 *
 * `onFilter` receives the lowercased query on every keystroke; the caller
 * owns showing/hiding its own rows. Autofocuses on mount. Click/keydown are
 * stopped from bubbling so typing (including Space/arrow keys) lands in the
 * input rather than triggering the host menu's own keyboard navigation.
 */
export function makeMenuSearchBox(onFilter: (query: string) => void, placeholder = 'Filter…', ownerDocument: Document = document): HTMLInputElement {
  const input = ownerDocument.createElement('input');
  input.type = 'text';
  input.placeholder = placeholder;
  input.setAttribute('aria-label', placeholder);
  Object.assign(input.style, {
    display:      'block',
    width:        'calc(100% - 20px)',
    margin:       '2px 10px 6px',
    padding: `${SPACE.xs} ${SPACE.md}`,
    fontSize:     FONT.body,
    boxSizing:    'border-box',
    background:   CLR.menuBg,
    color:        CLR.text,
    border:       `1px solid ${CLR.menuBorder}`,
    borderRadius: RADIUS.control,
    // Deliberate, and one of only two places the ring may be suppressed: this
    // input sits inside a menu whose border-radius/overflow CLIPS an outline,
    // so the ring cannot render here at all. The border-colour swap below is
    // the compensating indicator. See UI_STANDARDS.md — suppressing the ring is
    // permitted only where it cannot render, and only with a replacement.
    outline:      'none',
  } as Partial<CSSStyleDeclaration>);
  input.addEventListener('click', e => e.stopPropagation());
  input.addEventListener('mousedown', e => e.stopPropagation());
  input.addEventListener('keydown', e => e.stopPropagation());
  input.addEventListener('input', () => onFilter(input.value.trim().toLowerCase()));
  // Native outline suppressed above (it's clipped by the menu's own border-
  // radius/overflow) — replaced with a visible border-colour swap so keyboard
  // focus is never invisible.
  input.addEventListener('focus', () => { input.style.borderColor = CLR.iconActive; });
  input.addEventListener('blur',  () => { input.style.borderColor = CLR.menuBorder; });
  queueMicrotask(() => input.focus());
  return input;
}

/**
 * Build the plot-mode dropdown menu element.
 * Shared between renderWaferMap and renderWaferGallery.
 * The caller provides data-derived entry arrays and pick/active callbacks.
 */
export function buildModeMenuEl(
  anchorRect: DOMRect,
  testEntries: ModeEntry[],
  binEntries: ModeEntry[],
  stackedEntries: ModeEntry[],
  isCurrentEntry: (e: ModeEntry) => boolean,
  pickEntry: (entry: ModeEntry, menu: HTMLElement) => void,
  helpers: Pick<ToolbarHelpers, 'makeMenuRow' | 'makeMenuSection'>,
  currentMode: PlotMode,
  ownerWindow: Window = window,
  metadataEntries: ModeEntry[] = [],
): HTMLDivElement {
  const { makeMenuRow, makeMenuSection } = helpers;

  const menu = document.createElement('div');
  const modeMinWidth = 180;
  const modeFitsRight = anchorRect.left + modeMinWidth <= (ownerWindow.innerWidth ?? Infinity);
  const modeLeft = modeFitsRight ? anchorRect.left : Math.max(4, anchorRect.right - modeMinWidth);
  Object.assign(menu.style, {
    position:      'fixed',
    top:           `${anchorRect.bottom + 4}px`,
    left:          `${modeLeft}px`,
    background:    CLR.menuBg,
    border:        `1px solid ${CLR.menuBorder}`,
    borderRadius:  RADIUS.control,
    boxShadow:     SHADOW.menu,
    zIndex:        Z_BASE,
    minWidth:      `${modeMinWidth}px`,
    padding:       '4px 0',
    pointerEvents: 'auto',
  });

  // ── Test Value section ──────────────────────────────────────────────────────
  if (testEntries.length) {
    menu.appendChild(makeMenuSection('Test Value'));
    if (testEntries.length <= INLINE_TEST_LIMIT) {
      for (const entry of testEntries) {
        menu.appendChild(makeMenuRow(entry.label, isCurrentEntry(entry), true, e => {
          e.stopPropagation();
          pickEntry(entry, menu);
        }));
      }
    } else {
      const cascadeActive = currentMode === 'value';
      const cascadeRow = makeMenuRow(MODE_LABELS.value + ' ▶', cascadeActive, false, () => {});
      cascadeRow.style.display        = 'flex';
      cascadeRow.style.justifyContent = 'space-between';
      cascadeRow.style.alignItems     = 'center';
      let subMenu: HTMLDivElement | null = null;
      // Closing on mouseleave is deferred by a short grace period rather than
      // fired immediately: the submenu is rendered a couple pixels away from
      // cascadeRow (see subLeft below), so a straight-line move from the row
      // into the submenu crosses that gap over empty space — a mouseleave
      // with no useful relatedTarget — before mouseenter reaches the
      // submenu. Without the grace period that reads as "left the whole
      // cascade" and withdraws the submenu mid-move, making it very hard to
      // actually land a pointer on it. Any mouseenter on either the row or
      // the submenu itself cancels the pending close.
      let closeTimer: ReturnType<typeof setTimeout> | null = null;
      const cancelClose = () => { if (closeTimer !== null) { clearTimeout(closeTimer); closeTimer = null; } };
      const closeSub = () => { cancelClose(); subMenu?.remove(); subMenu = null; };
      const scheduleClose = () => { cancelClose(); closeTimer = setTimeout(closeSub, 300); };
      const openSub = () => {
        if (subMenu) return;
        const rowRect = cascadeRow.getBoundingClientRect();
        const subMinWidth = 160;
        const subMaxHeight = 320;
        const subFitsRight = rowRect.right + 2 + subMinWidth <= (ownerWindow.innerWidth ?? Infinity);
        const subLeft = subFitsRight ? rowRect.right + 2 : Math.max(4, rowRect.left - 2 - subMinWidth);
        const subTop = Math.min(rowRect.top - 4, Math.max(4, (ownerWindow.innerHeight ?? Infinity) - subMaxHeight - 4));
        subMenu = document.createElement('div');
        Object.assign(subMenu.style, {
          position:      'fixed',
          top:           `${subTop}px`,
          left:          `${subLeft}px`,
          background:    CLR.menuBg,
          border:        `1px solid ${CLR.menuBorder}`,
          borderRadius:  RADIUS.control,
          boxShadow:     SHADOW.menu,
          zIndex:        Z_ABOVE,
          minWidth:      `${subMinWidth}px`,
          maxHeight:     `${subMaxHeight}px`,
          overflowY:     'auto',
          padding:       '4px 0',
          pointerEvents: 'auto',
        });
        if (testEntries.length > MENU_SEARCH_THRESHOLD) {
          const searchBox = makeMenuSearchBox(query => {
            for (const row of testRows) {
              row.row.style.display = row.label.includes(query) ? '' : 'none';
            }
          }, 'Filter tests…');
          // Sticky, not a separate non-scrolling wrapper — subMenu is itself
          // the scroll container (overflowY: auto above), so this keeps the
          // box visible while the rows beneath it scroll.
          //
          // Contained: only needs to beat its own sibling rows inside
          // subMenu, which itself renders inside menuLayerFor's shared,
          // already-elevated layer — nothing outside subMenu competes against
          // this literal. See UI_STANDARDS.md's "position: sticky or fixed"
          // entry before reusing this pattern outside a menu.
          Object.assign(searchBox.style, { position: 'sticky', top: '0', zIndex: '1', background: CLR.menuBg } as Partial<CSSStyleDeclaration>);
          subMenu.appendChild(searchBox);
        }
        const testRows: { row: HTMLDivElement; label: string }[] = [];
        for (const entry of testEntries) {
          const row = makeMenuRow(entry.label, isCurrentEntry(entry), false, e => {
            e.stopPropagation();
            closeSub();
            pickEntry(entry, menu);
          });
          testRows.push({ row, label: entry.label.toLowerCase() });
          subMenu.appendChild(row);
        }
        subMenu.addEventListener('mouseenter', cancelClose);
        subMenu.addEventListener('mouseleave', scheduleClose);
        // Append into the same stacking root as the parent menu so the submenu
        // is visible when the menu is inside a maximized modal box (no real
        // fullscreen element exists — see openModal's CSS maximize).
        (menu.parentElement ?? ownerWindow.document.body).appendChild(subMenu);
        // Must listen on the submenu's own document, not the bare global —
        // a gallery card detached into a real popup window (see
        // renderWaferGallery.ts's openWindowForCard) has an entirely separate
        // `document` from the one this module first loaded in. Listening on
        // the wrong one means outside clicks inside the popup never reach
        // this handler, so the submenu never closes there (same class of bug
        // as overlayRootFor's own doc comment, and the identical fix used by the
        // collapsible-section `collapse` listener further down this file).
        ownerWindow.document.addEventListener('click', closeSub, { once: true });
      };
      cascadeRow.addEventListener('mouseenter', () => { cancelClose(); openSub(); });
      cascadeRow.addEventListener('mouseleave', scheduleClose);
      menu.appendChild(cascadeRow);
    }
  }

  // ── Bins section ────────────────────────────────────────────────────────────
  if (binEntries.length) {
    menu.appendChild(makeMenuSection('Bins'));
    for (const entry of binEntries) {
      menu.appendChild(makeMenuRow(entry.label, isCurrentEntry(entry), false, e => {
        e.stopPropagation();
        pickEntry(entry, menu);
      }));
    }
  }

  // ── Metadata section ────────────────────────────────────────────────────────
  if (metadataEntries.length) {
    menu.appendChild(makeMenuSection('Metadata'));
    for (const entry of metadataEntries) {
      menu.appendChild(makeMenuRow(entry.label, isCurrentEntry(entry), false, e => {
        e.stopPropagation();
        pickEntry(entry, menu);
      }));
    }
  }

  // ── Stacked (lot aggregation) section ───────────────────────────────────────
  if (stackedEntries.length) {
    menu.appendChild(makeMenuSection('Lot Aggregation'));
    for (const entry of stackedEntries) {
      menu.appendChild(makeMenuRow(entry.label, isCurrentEntry(entry), false, e => {
        e.stopPropagation();
        pickEntry(entry, menu);
      }));
    }
  }

  menu.setAttribute('role', 'menu');
  menu.setAttribute('aria-label', 'Plot mode');
  return menu;
}

