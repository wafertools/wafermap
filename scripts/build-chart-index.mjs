#!/usr/bin/env node
// Regenerates the chart index on docs/examples/insights.html (the "Chart gallery") from the chart catalogue
// (packages/stats/chartCatalogue.ts), so the page lists every chart, map and table the library draws from the one table the
// app's own "About this chart" lines are read from. The block between the chart-index markers is the script's; the rest of
// the page is written by hand.
//
// Reads the BUILT catalogue, so run `npm run build` first (`npm test` does, and tests/chartIndex.test.mjs fails when the
// block is out of date).
//
// Run:  node scripts/build-chart-index.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { fileURLToPath, pathToFileURL } from 'url';
import { dirname, resolve } from 'path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = resolve(root, 'docs/examples/insights.html');
const START = '<!-- chart-index:start (generated by scripts/build-chart-index.mjs from packages/stats/chartCatalogue.ts) -->';
const END = '<!-- chart-index:end -->';

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// Where each group of entries lives, in the order the page lists them.
const GROUPS = [
  { tab: 'overview', title: 'Overview', unit: 'card', blurb: 'Where the yield went, and which wafers differ.' },
  { tab: 'distributions', title: 'Distributions', unit: 'card', blurb: 'The shape of each measurement, not just its map colour. The comparison and the difference map appear once Group by is on.' },
  { tab: 'correlation', title: 'Correlation', unit: 'card', blurb: 'Which measurements move together — the question a wafer map cannot answer.' },
  { tab: 'plots', title: 'My plots', unit: 'chart', blurb: 'One of each chart a plot can be. New plot builds your own, and a saved plot draws on the next lot.' },
  { tab: 'data', title: 'Data', unit: 'table', blurb: 'The numbers behind the charts, to read, copy or export.' },
];

export async function renderIndex() {
  const { CHART_CATALOGUE } = await import(pathToFileURL(resolve(root, 'dist/packages/stats/chartCatalogue.js')).href);
  const thumb = id => existsSync(resolve(root, `docs/examples/thumbs/${id}.webp`));
  // A tile: the chart's thumbnail, its name and what it shows. Clicking it opens the live chart below (data-tab names the
  // Insights tab; the page script does the rest). A chart with no thumbnail is a name only.
  const tile = e => {
    const tab = e.tab === 'plots' ? 'plot' : e.tab;
    const img = thumb(e.id) ? `<img src="thumbs/${e.id}.webp" alt="" loading="lazy">` : '';
    return `        <a class="tile" href="#live" data-tab="${tab}" data-id="${e.id}" title="${esc(e.about)}">${img}<strong>${esc(e.title)}</strong><span>${esc(e.about)}</span></a>`;
  };
  const sections = GROUPS.map(g => {
    const entries = CHART_CATALOGUE.filter(e => e.tab === g.tab && e.id !== 'sweep');
    const n = entries.length;
    return `    <section>\n      <h3>${g.title} &mdash; ${n} ${g.unit}${n === 1 ? '' : 's'}</h3>\n      <p>${esc(g.blurb)}</p>\n      <div class="tiles">\n${entries.map(tile).join('\n')}\n      </div>\n    </section>`;
  });
  // The ways of colouring the wafer, a sweep and the picked-dies menu have their own pages: this page links to them rather than
  // drawing them again.
  const elsewhere = CHART_CATALOGUE.filter(e => (e.kind === 'map' && e.example) || e.id === 'sweep' || e.tab === 'drilldown');
  const pageOf = e => e.example ?? (e.id === 'sweep' ? 'sweeps.html' : 'drilldown.html');
  const chip = e => `        <a class="chip" href="${pageOf(e)}" title="${esc(e.about)}">${esc(e.title)}</a>`;
  sections.push(`    <section>\n      <h3>Shown on their own pages</h3>\n      <p>The maps, the sweeps and the menu on picked dies are not on this page; each has its own.</p>\n      <div class="chips">\n${elsewhere.map(chip).join('\n')}\n      </div>\n    </section>`);
  return `  ${START}\n  <div class="chart-index">\n${sections.join('\n')}\n  </div>\n  ${END}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = readFileSync(PAGE, 'utf8');
  const a = html.indexOf(START.slice(0, 40));
  const b = html.indexOf(END);
  if (a < 0 || b < 0) { console.error(`build-chart-index: the chart-index markers are missing from ${PAGE}`); process.exit(1); }
  const lineStart = html.lastIndexOf('\n', a) + 1;
  const next = html.slice(0, lineStart) + (await renderIndex()) + html.slice(b + END.length);
  if (process.argv.includes('--check')) {
    if (next !== html) { console.error('chart index out of date — run: node scripts/build-chart-index.mjs'); process.exit(1); }
    console.log('chart index up to date');
  } else {
    writeFileSync(PAGE, next);
    console.log('wrote the chart index to docs/examples/insights.html');
  }
}
